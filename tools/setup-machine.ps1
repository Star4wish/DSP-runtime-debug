<#
    setup-machine.ps1 -- one-time preparation after extracting this package on a new PC.

    What it does:
      1. Verifies the bundled toolchain (portable .NET SDK) and creates the writable
         scratch directories the build needs.
      2. Locates the game install (or accepts it via -GameDir / $env:DSP_GAME_DIR) and writes
         it to tools\machine.config, which every other script reads.
      3. Rewrites .mcp.json and generates MCP-REGISTRATION.txt with THIS machine's absolute
         paths, because MCP client configs need absolute paths.
      4. Optionally builds both projects and runs the offline test suites, so you know the
         package survived the trip before you rely on it.

    Usage:
        powershell -NoProfile -ExecutionPolicy Bypass -File tools\setup-machine.ps1
        ... -GameDir "D:\SteamLibrary\steamapps\common\Dyson Sphere Program"
        ... -SkipBuild      # only fix up paths
#>

param(
    [string]$GameDir = '',
    [switch]$SkipBuild,
    [switch]$SkipTests
)

$ErrorActionPreference = 'Stop'
. (Join-Path $PSScriptRoot 'dspenv.ps1')

$repoRoot = Split-Path $PSScriptRoot -Parent
$problems = @()

Write-Host "=== DSP runtime debugging environment: machine setup ===" -ForegroundColor Cyan
Write-Host ("  repo root : " + $repoRoot)
Write-Host ("  tools     : " + $DspWs)
Write-Host ""

# ---------------------------------------------------------------- 1. toolchain
Write-Host "[1/4] toolchain" -ForegroundColor Cyan
if (Test-Path $DspDotnet) {
    $sdkVersion = & $DspDotnet --version 2>&1
    Write-Host ("  OK    portable SDK: " + $sdkVersion)
}
else {
    Write-Host ("  FAIL  dotnet not found at " + $DspDotnet) -ForegroundColor Red
    Write-Host "        Extract the portable SDK into tools\dotnet-sdk (see README section 0)." -ForegroundColor Yellow
    $problems += 'portable .NET SDK missing'
}

foreach ($d in @('dotnet-home', 'nuget-packages', 'tmp', 'appdata', 'localappdata')) {
    $p = Join-Path $DspWs $d
    if (-not (Test-Path $p)) { New-Item -ItemType Directory -Force -Path $p | Out-Null }
}
Write-Host "  OK    scratch directories exist under tools\"

foreach ($rel in @('refs\Assembly-CSharp.dll', 'bepinex-lib\BepInEx.dll')) {
    $p = Join-Path $DspWs $rel
    if (Test-Path $p) { Write-Host ("  OK    reference assembly: " + $rel) }
    else {
        Write-Host ("  FAIL  missing reference assembly: " + $rel) -ForegroundColor Red
        $problems += "missing $rel"
    }
}

# A build needs the net472 reference assemblies package in the local NuGet cache when the
# machine is offline; warn early rather than failing deep inside MSBuild.
$cacheHint = Join-Path $DspWs 'nuget-packages\microsoft.netframework.referenceassemblies.net472'
if (Test-Path $cacheHint) { Write-Host "  OK    net472 reference assemblies are cached (offline build possible)" }
else { Write-Host "  WARN  net472 reference assemblies are not cached: the first build will need internet" -ForegroundColor Yellow }

# ---------------------------------------------------------------- 2. game directory
Write-Host ""
Write-Host "[2/4] game directory" -ForegroundColor Cyan

$resolved = ''
if (-not [string]::IsNullOrWhiteSpace($GameDir)) {
    if (Test-Path (Join-Path $GameDir 'DSPGAME.exe')) { $resolved = $GameDir }
    else { Write-Host ("  FAIL  no DSPGAME.exe under " + $GameDir) -ForegroundColor Red; $problems += 'bad -GameDir' }
}
else {
    $resolved = Resolve-DspGameDir
}

if ([string]::IsNullOrWhiteSpace($resolved)) {
    Write-Host "  WARN  game directory not found automatically." -ForegroundColor Yellow
    Write-Host "        Building the plugin needs it; the MCP server does not." -ForegroundColor Yellow
    Write-Host "        Set it later with:  `$env:DSP_GAME_DIR = '<path>'" -ForegroundColor Yellow
    $resolved = ''
}
else {
    Write-Host ("  OK    " + $resolved)
    $logPath = Join-Path $resolved 'BepInEx\LogOutput.log'
    if (Test-Path $logPath) { Write-Host "  OK    BepInEx has run here before (LogOutput.log present)" }
    else { Write-Host "  INFO  BepInEx has not run yet on this machine; the game-side files still need installing (see README section 3)" -ForegroundColor Yellow }
}

# Persist the answer so other scripts and future shells agree.
$machineConfig = Join-Path $DspWs 'machine.config.ps1'
$escaped = $resolved.Replace("'", "''")
@(
    '# Generated by tools\setup-machine.ps1. Machine-specific paths live here so that',
    '# nothing else in the tree has to be edited. Delete this file to re-detect.',
    ("`$env:DSP_GAME_DIR = '" + $escaped + "'")
) | Set-Content -Path $machineConfig -Encoding ASCII
Write-Host ("  OK    wrote " + $machineConfig)

# ---------------------------------------------------------------- 3. MCP client registration
Write-Host ""
Write-Host "[3/4] MCP client registration" -ForegroundColor Cyan

$launcher = Join-Path $DspWs 'run-dsp-mcp.cmd'
$mcpJsonPath = Join-Path $repoRoot '.mcp.json'
$mcpJson = [ordered]@{
    'mcpServers' = [ordered]@{
        'dsp-bridge' = [ordered]@{
            type        = 'stdio'
            command     = $launcher
            args        = @()
            env         = @{}
            timeout     = 30000
            description = 'DSP runtime debugging bridge: read live game state and issue L0/L1 debug actions. Requires the in-game DspBridge plugin; when the game is closed the tools return a readable business error.'
        }
    }
}
$mcpJson | ConvertTo-Json -Depth 8 | Set-Content -Path $mcpJsonPath -Encoding UTF8
Write-Host ("  OK    .mcp.json rewritten with this machine's launcher path")

$registration = @"
MCP client registration -- generated by tools\setup-machine.ps1
================================================================

Server name : dsp-bridge
Transport   : stdio (the client starts and stops this process)
Command     : $launcher
Args        : (none)
Timeout     : 30000 ms

--------------------------------------------------------------------------------
Claude Code, one command
--------------------------------------------------------------------------------
claude mcp add --transport stdio dsp-bridge -- "$launcher"
claude mcp list

--------------------------------------------------------------------------------
Claude Code, project file
--------------------------------------------------------------------------------
$mcpJsonPath

    {
      "mcpServers": {
        "dsp-bridge": {
          "type": "stdio",
          "command": "$($launcher.Replace('\','\\'))",
          "args": [],
          "timeout": 30000
        }
      }
    }

--------------------------------------------------------------------------------
Codex CLI  (~/.codex/config.toml)
--------------------------------------------------------------------------------
[mcp_servers.dsp-bridge]
command = "$($launcher.Replace('\','\\'))"
args = []
startup_timeout_sec = 30
tool_timeout_sec = 120
# Hide the single write tool from the model entirely:
# disabled_tools = ["dsp_set_pause"]

--------------------------------------------------------------------------------
Any other MCP client
--------------------------------------------------------------------------------
command: $launcher
args   : none
env    : none required

NOTES
  * Do NOT point the client at "dotnet run --project ...": that needs MSBuild and a NuGet
    restore at launch time. run-dsp-mcp.cmd sets up the portable toolchain and runs the
    built dll directly.
  * The game writes its port and token to %LOCALAPPDATA%\DSPBridge\runtime.json. The MCP
    server reads that file on every call, so no token needs to be configured here.
  * If you move this folder, re-run tools\setup-machine.ps1 to refresh the paths.
"@
$registrationPath = Join-Path $repoRoot 'MCP-REGISTRATION.txt'
$registration | Set-Content -Path $registrationPath -Encoding UTF8
Write-Host ("  OK    wrote " + $registrationPath)

# ---------------------------------------------------------------- 4. build + tests
Write-Host ""
Write-Host "[4/4] build and offline tests" -ForegroundColor Cyan

if ($SkipBuild) {
    Write-Host "  skipped (-SkipBuild)"
}
elseif ($problems.Count -gt 0) {
    Write-Host ("  skipped: fix these first -> " + ($problems -join '; ')) -ForegroundColor Yellow
}
else {
    foreach ($proj in @('DspBridge\DspBridge.csproj', 'DspMcpBridge\DspMcpBridge.csproj')) {
        $full = Join-Path $repoRoot $proj
        Write-Host ("  building " + $proj)
        & $DspDotnet build $full -c Release -v quiet
        if ($LASTEXITCODE -ne 0) { $problems += "build failed: $proj" }
    }

    if (-not $SkipTests -and $problems.Count -eq 0) {
        Write-Host "  running offline suites (game not required)"
        $out = & powershell -NoProfile -ExecutionPolicy Bypass -File (Join-Path $PSScriptRoot 'test-all.ps1') 2>&1 | Out-String
        if ($out -match 'ALL SUITES PASSED') { Write-Host "  OK    all offline suites passed" -ForegroundColor Green }
        else {
            Write-Host "  FAIL  offline suites reported a problem (full output below)" -ForegroundColor Red
            Write-Host $out
            $problems += 'offline test suites failed'
        }
    }
    elseif ($SkipTests) { Write-Host "  tests skipped (-SkipTests)" }
}

Write-Host ""
Write-Host "=== summary ===" -ForegroundColor Cyan
if ($problems.Count -eq 0) {
    Write-Host "MACHINE SETUP COMPLETE" -ForegroundColor Green
    Write-Host ""
    Write-Host "Next steps:" -ForegroundColor Yellow
    Write-Host "  1. make sure the in-game side is installed (README section 3)"
    Write-Host "  2. start the game, load a SAVE (not the main menu)"
    Write-Host "  3. powershell -NoProfile -ExecutionPolicy Bypass -File tools\verify-live.ps1"
    Write-Host "  4. register the MCP server using MCP-REGISTRATION.txt"
    exit 0
}

Write-Host "SETUP INCOMPLETE:" -ForegroundColor Red
$problems | ForEach-Object { Write-Host ("  - " + $_) -ForegroundColor Red }
exit 1
